"""Write the Black Ops audio decoder's entropy books and exponent bands as Rust.

The table in crates/asset_audio/src/wma_t5/table.rs was generated by this
script from the binary map that used to sit beside the decoder
(crates/asset_audio/src/wma_t5/format.bin, added in commit 65052d3f51).
To regenerate it:

    git show 65052d3f51:crates/asset_audio/src/wma_t5/format.bin > format.bin
    python3 scripts/wma_t5_table.py format.bin > crates/asset_audio/src/wma_t5/table.rs
    cargo fmt --all

The map is little endian: an 8-byte "WM2MAP" header, a book count, then
each book's entry count and entries (prefix boundary u32, code width u8,
operation u8, zero run u16, value i16), then a band grid count and each
grid's sample rate u32, block size u16, band count u16 and band widths
(u16 each).
"""

import struct
import sys

HEADER = """//! The Black Ops audio decoder's entropy books and exponent band grids,
//! generated by `scripts/wma_t5_table.py` (see it for the source and how to
//! regenerate). Do not edit by hand.

/// Each book's entries: the 24-bit prefix boundary, the code width in
/// bits, the operation, the zero run and the value.
pub(super) const BOOKS: &[&[(u32, u8, u8, u16, i16)]] = &[
"""


def read(data, offset, fmt):
    values = struct.unpack_from("<" + fmt, data, offset)
    return values, offset + struct.calcsize("<" + fmt)


def main(path):
    with open(path, "rb") as blob:
        data = blob.read()
    if data[:6] != b"WM2MAP":
        sys.exit("not a WM2MAP file")
    offset = 8
    out = [HEADER]
    (books,), offset = read(data, offset, "H")
    for _ in range(books):
        (count,), offset = read(data, offset, "H")
        out.append("    &[\n")
        for _ in range(count):
            entry, offset = read(data, offset, "IBBHh")
            out.append("        ({}, {}, {}, {}, {}),\n".format(*entry))
        out.append("    ],\n")
    out.append("];\n\n")
    out.append("/// Each grid's sample rate, block size and band widths.\n")
    out.append("pub(super) const BANDS: &[(u32, usize, &[usize])] = &[\n")
    (grids,), offset = read(data, offset, "H")
    for _ in range(grids):
        (rate, size, count), offset = read(data, offset, "IHH")
        widths, offset = read(data, offset, f"{count}H")
        out.append(f"    ({rate}, {size}, &{list(widths)}),\n")
    out.append("];\n")
    if offset != len(data):
        sys.exit(f"{len(data) - offset} trailing bytes")
    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
