const UNBOUNDED: i32 = i32::MAX;

const fn spec(
    name: &'static str,
    min_params: i32,
    max_params: i32,
    developer: bool,
) -> BuiltinSpec {
    BuiltinSpec {
        name,
        min_params,
        max_params,
        developer,
    }
}

